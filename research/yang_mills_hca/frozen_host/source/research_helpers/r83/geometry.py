"""Metric-dependent quotient on the JOINT R4 state + SO(2)^2 link-angle chart.

Coordinate z=(A[4,4],B[4,4],lambda*theta[reciprocal-paired undirected edge,plane]).
The local SO(2)^2 per-node gauge action has eight infinitesimal generators.
This is a *fixed-link-dynamics* state-and-link configuration quotient, not a
metric derived from physical Yang-Mills dynamics or a stability theorem.
"""
from __future__ import annotations
import math
import torch
from r82 import geometry as local

def edge_table(adj):
    """Use one orientation per independently represented reciprocal link pair.

    Repeated parallel links are paired by original ordinal, as generated by the
    frozen source's sorted shared-participant link_builder. Reject missing or
    noninverse reverse links; no free coordinate is granted to both directions.
    """
    full={}
    for dst in sorted(adj):
        src,op=adj[dst]
        for i,ss in enumerate(src):
            ss=int(ss);dst=int(dst)
            if not (0<=dst<4 and 0<=ss<4 and dst!=ss):raise ValueError('INVALID_EDGE')
            U=op[i].to(torch.float64)
            if U.shape!=(4,4) or not bool(torch.isfinite(U).all()):raise ValueError('INVALID_LINK')
            angle=[]
            for j in (0,2):
                c=float(U[j,j]);v=float(U[j+1,j]);a=math.atan2(v,c)
                block=torch.tensor([[math.cos(a),-math.sin(a)],[math.sin(a),math.cos(a)]],dtype=torch.float64)
                if float((U[j:j+2,j:j+2]-block).abs().amax())>1e-9:raise ValueError('LINK_NOT_SO2')
                angle.append(a)
            if float(U[:2,2:].abs().amax())>1e-10 or float(U[2:,:2].abs().amax())>1e-10:raise ValueError('LINK_CROSS_PLANE')
            full.setdefault((dst,ss),[]).append((tuple(angle),U))
    result=[]
    for dst,ss in sorted(full):
        if (ss,dst) not in full or len(full[(dst,ss)])!=len(full[(ss,dst)]):raise ValueError('RECIPROCAL_LINK_MISSING')
        if dst>=ss:continue
        for i,(angles,U) in enumerate(full[(dst,ss)]):
            reverse=full[(ss,dst)][i][1]
            if float((U.T-reverse).abs().max())>1e-9:raise ValueError('RECIPROCAL_INVERSE_DRIFT')
            result.append((dst,ss,angles))
    if not result:raise ValueError('EMPTY_GRAPH')
    return result

def link_angles(adj,t=torch):
    return t.tensor([e[2] for e in edge_table(adj)],dtype=t.float64).reshape(-1)

def generators(state,edges,lam,t=torch):
    if not 0<lam<=10:raise ValueError('METRIC_SCALE')
    n=state[0].shape[0]
    if state[0].shape!=state[1].shape or state[0].shape[-2:]!=(4,4):raise ValueError('STATE_SHAPE')
    nlink=2*len(edges);dim=32+nlink
    mat=t.zeros((n,dim,8),dtype=t.float64)
    for node in range(4):
        for plane in range(2):
            k=2*node+plane
            v=local.flatten(local.tangent(state,node,plane,t),t)
            mat[:,:32,k]=v
            for e,(dst,src,_) in enumerate(edges):
                mat[:,32+2*e+plane,k]=lam*((dst==node)-(src==node))
    return mat

def quotient(state,edges,lam,t=torch):
    v=generators(state,edges,lam,t)
    u,s,_=t.linalg.svd(v,full_matrices=False)
    if not bool(t.isfinite(s).all()) or float(s[:,-1].min())<=1e-10:raise ValueError('DEGENERATE_LOCAL_ORBIT')
    p=t.eye(v.shape[1],dtype=t.float64)-u@u.transpose(-2,-1)
    return p,s,v

def tangent_transport(state,gs,link_count,t=torch):
    """Derivative representation of gauge change in joint scaled coordinates."""
    n=state[0].shape[0];d=32+2*link_count
    r=t.eye(d,dtype=t.float64)
    for ch in (0,1):
        for node in range(4):
            sl=16*ch+4*node
            r[sl:sl+4,sl:sl+4]=gs[node]
    return r

def metric_audit(state,adj,lam,t=torch):
    edges=edge_table(adj);p,sv,gen=quotient(state,edges,lam,t)
    d=p.shape[-1]
    idem=(p@p-p).abs().amax()
    sym=(p-p.transpose(-2,-1)).abs().amax()
    null=(p@gen).abs().amax()
    gs=local.rotation(1,0,0.137,t)
    st=local.transform_state(state,gs,t)
    adj2=local.transform_links(adj,gs,t)
    edges2=edge_table(adj2)
    if [(d,s) for d,s,_ in edges] != [(d,s) for d,s,_ in edges2]:raise ValueError('EDGE_ORDER_DRIFT')
    # Link angle action is additive (mod 2pi). Compare group action modulo 2pi.
    before=link_angles(adj,t);after=link_angles(adj2,t)
    add=[]
    for dst,src,_ in edges:
        add.extend([.137*((dst==1)-(src==1)),0.])
    delta=after-before-t.tensor(add,dtype=t.float64)
    link_error=t.atan2(t.sin(delta),t.cos(delta)).abs().amax()
    p2,sv2,gen2=quotient(st,edges2,lam,t)
    r=tangent_transport(st,gs,len(edges),t)
    cov=(p2-r@p@r.T).abs().amax()
    svcov=(sv2-sv).abs().amax()
    # A single state-only probe, shared across all lambda values; its horizontal
    # norm is genuinely dependent on the chosen state/link metric.
    probe=t.zeros(d,dtype=t.float64);probe[0]=1.;probe[17]=.7
    phys=t.linalg.vector_norm(t.einsum('bij,j->bi',p,probe),dim=-1)
    probe2=r@probe
    phys2=t.linalg.vector_norm(t.einsum('bij,j->bi',p2,probe2),dim=-1)
    invariant=(phys-phys2).abs().amax()
    return {'dimension':d,'link_count':len(edges),'local_rank':8,'quotient_rank':d-8,
            'smallest_generator_sv':float(sv[:,-1].min()),
            'idempotence':float(idem),'symmetry':float(sym),'horizontal_null':float(null),
            'gauge_covariance':float(cov),'generator_sv_covariance':float(svcov),
            'link_action_error':float(link_error),'probe_invariance':float(invariant),
            'horizontal_state_probe_mean':float(phys.mean())}
