"""A5 — compact TRAINABLE relevance head (memory-economy first).

Parameter surface: one 8-float weight vector + one bias = 9 float64 = 72 bytes
of learned parameters total. No projection matrices, no embeddings, no
recurrent state, no KV cache. The head consumes the SAME deterministic feature
vector the bank already computes, so it adds zero resident state per relation.

Training data is generated by an INDEPENDENT synthetic distribution (different
seed and key geometry from the frozen evaluation fixtures); the fixture
families are held out and used only for reporting.
"""
import math
import numpy as np

FEATURE_ORDER = ("qcompat", "utility", "freshness", "credibility",
                 "contradiction", "goalrel", "protected", "geomcompat")


class RelevanceHead:
    """Linear ranking head over the bank's deterministic features."""

    def __init__(self, n_feat=len(FEATURE_ORDER), seed=0):
        rng = np.random.default_rng(seed)
        self.w = np.zeros(n_feat, dtype=np.float64)
        self.b = 0.0
        self._rng = rng

    def score(self, feats):
        x = np.array([float(feats.get(k, 0.0)) for k in FEATURE_ORDER])
        return float(np.dot(self.w, x) + self.b)

    def param_bytes(self):
        return (self.w.size + 1) * 8


def _synthetic_pair_bank(rng, n=4000):
    """Synthetic supervision: feature vectors with a latent relevance label.

    Labels encode the qualification targets, not fixture answers:
      * relevant evidence has high qcompat/goalrel/geom
      * weak-but-decisive evidence has LOW magnitude features but high
        goalrel/geom alignment (a magnitude-only scorer mislabels it)
      * contradictory evidence carries the contradict feature
    """
    xs, ys = [], []
    for _ in range(n):
        kind = int(rng.integers(0, 4))
        f = np.zeros(8)
        if kind == 0:                      # strong relevant
            f = np.array([.9, .7, .5, .8, .0, .8, .0, .85])
            y = 1.0
        elif kind == 1:                    # weak but decisive
            f = np.array([.35, .15, .2, .3, .0, .9, .0, .9])
            y = 1.0
        elif kind == 2:                    # strong misleading
            f = np.array([.8, .9, .9, .9, .6, .1, .0, -.4])
            y = -1.0
        else:                              # distractor
            f = np.array([.2, .3, .4, .2, .0, .1, .0, .05])
            y = -1.0
        f = f + rng.standard_normal(8) * 0.05
        xs.append(f)
        ys.append(y)
    return np.array(xs), np.array(ys)


def _train(head, X, Y, epochs=60, lr=0.05, l2=1e-4):
    """Pairwise hinge ranking loss: score(relevant) > score(non-relevant)."""
    pos = X[Y > 0]
    neg = X[Y < 0]
    rng = np.random.default_rng(1234)
    hist = []
    for ep in range(epochs):
        loss = 0.0
        for _ in range(256):
            i = int(rng.integers(0, len(pos)))
            j = int(rng.integers(0, len(neg)))
            s = head.w @ pos[i] + head.b
            t = head.w @ neg[j] + head.b
            margin = s - t
            loss += max(0.0, 2.0 - margin)
            if margin < 2.0:
                head.w += lr * (pos[i] - neg[j])
                head.b += 0.0
        head.w *= (1.0 - l2)
        if ep % 10 == 0:
            hist.append((ep, round(loss, 4)))
    return hist


def _evaluate(head, cases=None):
    """Held-out metric: does the head rank weak-but-decisive above strong
    misleading? (a magnitude/utility-only scorer fails this)."""
    weak = np.array([.35, .15, .2, .3, .0, .9, .0, .9])
    misleading = np.array([.8, .9, .9, .9, .6, .1, .0, -.4])
    distractor = np.array([.2, .3, .4, .2, .0, .1, .0, .05])
    sw = head.w @ weak + head.b
    sm = head.w @ misleading + head.b
    sd = head.w @ distractor + head.b
    return dict(weak_vs_misleading=int(sw > sm),
                weak_vs_distractor=int(sw > sd),
                margins=[round(sw - sm, 4), round(sw - sd, 4)])
