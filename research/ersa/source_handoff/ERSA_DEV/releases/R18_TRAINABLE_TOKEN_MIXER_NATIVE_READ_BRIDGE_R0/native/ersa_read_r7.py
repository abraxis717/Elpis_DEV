"""R7 prototype: native-feature/native-rank/native-reduce, R5 authority in host.

Not a neural model, SSC adapter, or autonomous semantic selector.
The bank's bounded discovery and admission checks are never bypassed.
Only immutable return values are exposed; reject entire read on stale stage.
"""
from __future__ import annotations
from dataclasses import dataclass
from typing import Optional
import numpy as np
from elpis_ersa import contract_ersa as C
from native.ersa_native import NativeError


@dataclass(frozen=True)
class ReadResult:
    status: str
    code: str
    relation_ids: tuple = ()
    salient: tuple = ()
    collective: tuple = ()
    scanned: int = 0
    discovered: int = 0
    evidence: tuple = ()


def _reject(code):
    return ReadResult('REJECTED',code)


class NativeReadPath:
    def __init__(self,ops):
        self.ops=ops

    def read(self, bank, query_key, query_goal=None, *, qdir=None,
             k=None, exact_relation_id=None):
        if not bank._open or bank._halted:
            return _reject('NO_ACTIVE_SESSION')
        spec=bank._spec
        if spec.key_feature_dim!=4:
            return _reject('UNSUPPORTED_DIMENSION')
        if bank._modes['selection']!='ersa':
            return _reject('UNSUPPORTED_SELECTION_MODE')
        if k is None:k=spec.max_candidates
        if type(k) is not int or not 1<=k<=spec.max_candidates:
            return _reject('INVALID_K')
        try:
            qk=C.key_features(query_key,4)
            qd=C.vec4(qdir if qdir is not None else qk,spec.finite_bound)
            if query_goal is not None:
                qg=C.vec4(query_goal,spec.finite_bound)
            else:qg=None
        except (C._Invalid,ValueError,TypeError):
            return _reject('INVALID_QUERY')
        # Charge exactly one outer selection op, then bank discovery's op.
        # No read is accepted if either upstream budget is exhausted.
        if not bank._budget():return _reject('OP_BUDGET')
        epoch,tick=bank._epoch,bank._tick
        original_authority=bank._authority.copy()
        original_registry=bank._registry
        out=bank.query_candidates(qk,qg,None,limit=spec.max_candidates,
                                  qdir=qd,exact_relation_id=exact_relation_id)
        if out.status!=C.STATUS_OK:
            return _reject(out.code)
        slots=list(bank._last_slots)
        a=bank._arrays
        selected=[]
        for s in slots:
            if s<0 or s>=spec.max_active_relations or not a['live'][s]:
                return _reject('STALE_SLOT')
            rid=int(a['rid'][s]);prov=int(a['prov'][s])
            if not bank._admitted_rid(rid) or prov in bank._authority['denied']:
                continue
            v=bank._transported_value(s)
            if v is None:continue
            selected.append((s,rid,int(a['revision'][s]),tuple(v)))
        # R5 select() filters denied/unbound candidates; never confer authority
        # on another record merely because its score is geometrically similar.
        if not selected:
            return ReadResult('OK','',(),(0.,)*4,(0.,)*4,len(slots),0,())
        if len(selected)>8192:return _reject('CAPACITY_EXCEEDED')
        idx=[z[0] for z in selected]
        try:
            key=np.asarray(a['key'][idx],dtype=np.float64)
            goal=np.asarray(a['goal'][idx],dtype=np.float64)
            vec=np.asarray([z[3] for z in selected],dtype=np.float64)
            meta=np.asarray([[float(a['util'][s]),float(a['cred'][s]),
                  -1.0 if (bank._slot_of(int(a['contra'][s])) is not None and
                             bank._admitted_rid(int(a['contra'][s]))) else 0.0,
                  1.0 if bank._is_protected(s) else 0.0] for s in idx],dtype=np.float64)
            issued=np.asarray(a['issued'][idx],dtype=np.int64)
            features=self.ops.features(key,goal,vec,meta,issued,tick,
                         spec.halflife_ticks,qk,qg,qd)
            scores=self.ops.score(features)
            # Python's R5 contract: round(score,12) and relation_id tie-break.
            # Safe recalibration for rare numerical half-way ties. Otherwise
            # the actual score remains generated by C, not bank._score().
            canonical=[]
            for fs,raw in zip(features,scores):
                scaled=float(raw)*1e12
                dist=abs(scaled-(int(np.floor(scaled))+.5))
                if dist<0.0001:
                    import math
                    raw=math.fsum(float(fs[j])*w for j,w in enumerate(
                           (1.,.5,.35,.4,-.6,.45,.3,.55)))
                canonical.append(round(float(raw),12))
            ids=[z[1] for z in selected]
            order=self.ops.rank(canonical,ids,[1]*len(ids),k)
            chosen=[selected[j] for j in order]
            v=[z[3] for z in chosen]
            w=[float(scores[j]) for j in order]
            salient,collective=self.ops.aggregate(v,w)
        except (NativeError,TypeError,ValueError,OverflowError,FloatingPointError) as exc:
            return _reject('NATIVE_INPUT_OR_KERNEL_FAILURE:'+type(exc).__name__)
        if (bank._epoch!=epoch or bank._tick!=tick or
                bank._registry is not original_registry or bank._authority!=original_authority):
            return _reject('MID_READ_AUTHORITY_CHANGE')
        for s,rid,revision,tv in selected:
            if (not a['live'][s] or int(a['rid'][s])!=rid or
                int(a['revision'][s])!=revision or
                not bank._admitted_rid(rid) or
                int(a['prov'][s]) in bank._authority['denied'] or
                bank._transported_value(s)!=tv):
                return _reject('MID_READ_REVISION_CHANGE')
        evidence=tuple((z[1],float(scores[j])) for j,z in
                        ((p,selected[p]) for p in order))
        return ReadResult('OK','',tuple(z[1] for z in chosen),
                          tuple(salient),tuple(collective),len(slots),
                          len(selected),evidence)
